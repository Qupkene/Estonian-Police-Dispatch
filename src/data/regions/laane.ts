const t = (et: string, en: string): Text => ({ et, en });

interface PlaceOpts {
  district?: string;
  tags?: string[];
  zone?: string;
}

function place(
  id: string,
  name: string,
  kind: PlaceKind,
  city: string,
  address: string,
  coord: LngLat,
  opts: PlaceOpts = {},
): Place {
  return { id, name, kind, city, address, coord, ...opts };
}

function street(
  id: string,
  name: string,
  city: string,
  district: string | undefined,
  kind: Street['kind'],
  houses: [number, number],
  points: LngLat[],
  weight = 1,
  zone?: string,
): Street {
  const s: Street = { id, name, city, points, houses, kind, weight };
  if (district) s.district = district;
  if (zone) s.zone = zone;
  return s;
}

